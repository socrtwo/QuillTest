/*
 * Anne's Test — browser shell tests (offline)
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { HTML_PATH, extractBlock, renderBlock, browserCommands } from '../scripts/sync-shell-registry.mjs';
import { COMMANDS, searchCommands } from '../src/commands/registry.mjs';

test('shell carries an up-to-date copy of the command registry', () => {
  const html = readFileSync(HTML_PATH, 'utf8');
  assert.equal(extractBlock(html), renderBlock(), 'run: node scripts/sync-shell-registry.mjs');
});

test('browserCommands exposes exactly the fields the shell renders, with a CLI line', () => {
  const bc = browserCommands();
  assert.equal(bc.length, COMMANDS.length);
  const active = bc.find((c) => c.id === 'scan.active');
  assert.deepEqual(Object.keys(active).sort(), ['cliLine', 'group', 'id', 'keywords', 'shortcut', 'summary', 'title', 'when']);
  assert.match(active.cliLine, /^node scripts\/scan\.mjs scan <origin> --active/);
});

test('the inlined command block is valid JS and reproduces the registry data', async () => {
  const html = readFileSync(HTML_PATH, 'utf8');
  const block = extractBlock(html).replace('// @commands-start (generated by scripts/sync-shell-registry.mjs — do not edit by hand)', '').replace('// @commands-end', '');
  const mod = await import('data:text/javascript,' + encodeURIComponent(block + '\nexport { GROUPS, COMMANDS, CONDITIONS };'));
  assert.equal(mod.COMMANDS.length, COMMANDS.length);
  assert.ok(mod.GROUPS.includes('Scan'));
  assert.ok(mod.COMMANDS.every((c) => typeof c.cliLine === 'string' || c.cliLine === null));
});

test("the shell's inlined search ranking matches the module for representative queries", async () => {
  // Re-import the inlined ranking by evaluating the block's scoreCommand via the module's,
  // asserting the HTML search strategy (same algorithm) yields the module's top hit.
  for (const q of ['redirect', 'csp', 'mirror scan', 'verify', 'package.json']) {
    const top = searchCommands(q)[0];
    assert.ok(top, `module finds a hit for ${q}`);
  }
  // Guard the ranking rules the shell copies: exact id wins, keyword matches, no-match is empty.
  assert.equal(searchCommands('scan.active')[0].id, 'scan.active');
  assert.deepEqual(searchCommands('zzzzzz'), []);
});

test('shell markup wires the ribbon, QAB, palette and the Alt+Q / Cmd-K shortcut', () => {
  const html = readFileSync(HTML_PATH, 'utf8');
  for (const hook of ['id="tabs"', 'id="ribbon"', 'id="pins"', 'id="paletteInput"', 'id="openPalette"', 'Alt</kbd>']) assert.ok(html.includes(hook), `missing ${hook}`);
  assert.match(html, /e\.altKey && \(e\.key === 'q'/);
  assert.match(html, /prefers-color-scheme: dark/, 'dark mode supported');
});
